def get_subtopics(skill_id: str, label: str) -> list[str]:
    return SUBTOPICS.get(skill_id, [label])


def shortest_learning_order(start_known: list[str], goal_id: str) -> list[str]:
    """
    Ancestors of goal_id (all transitive prerequisites), minus anything the
    learner already knows, topologically sorted (Kahn's algorithm) so every
    dependency comes before what depends on it.
    """
    if goal_id not in SKILLS:
        return []
    known = set(start_known)

    ancestors: set[str] = set()

    def collect(sid: str) -> None:
        for p in SKILLS[sid].prereqs:
            if p not in ancestors:
                ancestors.add(p)
                collect(p)

    collect(goal_id)
    ancestors.add(goal_id)

    needed = [sid for sid in ancestors if sid not in known]
    needed_set = set(needed)

    in_degree = {sid: 0 for sid in needed}
    adj: dict[str, list[str]] = {sid: [] for sid in needed}
    for sid in needed:
        for p in SKILLS[sid].prereqs:
            if p in needed_set:
                adj[p].append(sid)
                in_degree[sid] += 1

    queue = [sid for sid in needed if in_degree[sid] == 0]
    order: list[str] = []
    while queue:
        sid = queue.pop(0)
        order.append(sid)
        for nxt in adj[sid]:
            in_degree[nxt] -= 1
            if in_degree[nxt] == 0:
                queue.append(nxt)

    return order if len(order) == len(needed) else needed


