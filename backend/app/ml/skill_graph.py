"""
Skill taxonomy + prerequisite graph.

This is the backbone of the recommendation engine: every course in
app/data/courses.json is tagged with one or more of these skill ids, and
every learning path is generated by walking this DAG from what the learner
already knows to the skill that matches their goal.

Each skill node has:
- label:    human readable name
- domain:   which broader track it belongs to (used for the "career path"
            picker on the profile/onboarding screen)
- level:    foundation | core | advanced  (used to order stages)
- keywords: phrases used by the TF-IDF goal matcher to tag free-text goals
- prereqs:  skill ids that must come before this one
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class SkillNode:
    id: str
    label: str
    domain: str
    level: str  # foundation | core | advanced
    keywords: list[str] = field(default_factory=list)
    prereqs: list[str] = field(default_factory=list)


SKILLS: dict[str, SkillNode] = {}


def _add(id_: str, label: str, domain: str, level: str,
         keywords: list[str], prereqs: list[str] | None = None) -> None:
    SKILLS[id_] = SkillNode(id_, label, domain, level, keywords, prereqs or [])


